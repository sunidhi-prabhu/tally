/** Contracts require participants sorted ascending; core's result does not depend on order. */
const sortAddresses = (list: MemberId[]) => [...list].sort();

function buildFixture() {
  return {
    note: "Generated by packages/core/src/contract-fixtures.test.ts. Do not edit by hand.",
    scenarioCount: scenarios.length,
    scenarios: scenarios.map((scenario, s) => {
      const group: Group = {
        id: `g${s}`,
        name: scenario.name,
        members: scenario.members,
      };
      const entries: LedgerEntry[] = [];
      const ops = scenario.ops.map((op, i) => {
        let actor: MemberId;
        let from = addr("0");
        let to = addr("0");
        let participants: MemberId[] = [];
        let shares: bigint[] = [];
        if (op.kind === "settlement") {
          entries.push({
            kind: "settlement",
            settlement: {
              id: `s${i}`,
              groupId: group.id,
              from: op.from,
              to: op.to,
              amount: op.amount,
              kind: op.via,
            },
          });
          // The caller on-chain: the debtor pays with tokens; the creditor acknowledges.
          actor = op.via === "token" ? op.from : op.to;
          from = op.from;
          to = op.to;
        } else {
          const expense = createExpense(group, `e${i}`, {
            payer: op.payer,
            amount: op.amount,
            split:
              op.kind === "equal"
                ? {
                    type: "equal",
                    participants: sortAddresses(op.participants),
                  }
                : {
                    type: "custom",
                    shares: sortAddresses(Object.keys(op.shares)).map(
                      (member) => ({
                        member,
                        amount: op.shares[member]!,
                      }),
                    ),
                  },
          });
          entries.push({ kind: "expense", expense });
          actor = op.payer;
          participants = expense.shares.map((share) => share.member);
          shares = expense.shares.map((share) => share.amount);
        }
        const nets = computeBalances(group, entries);
        return {
          kind: op.kind === "settlement" ? op.via : op.kind,
          actor,
          from,
          to,
          amount: op.amount.toString(),
          participants,
          shares: shares.map(String),
          netsAfter: nets.map((b) => b.net.toString()),
        };
      });
      return {
        name: scenario.name,
        members: scenario.members,
        opCount: ops.length,
        ops,
      };
    }),
  };
}

describe("contract fixtures", () => {
  it("lowercase hex addresses sort in numeric order", () => {
    expect(sortAddresses([CAROL, ALICE, DAVE, BOB])).toEqual([
      BOB,
      DAVE,
      ALICE,
      CAROL,
    ]);
  });

  it("matches packages/contracts/test/fixtures/core-fixtures.json", async () => {
    const json = `${JSON.stringify(buildFixture(), null, 2)}\n`;
    await expect(json).toMatchFileSnapshot(
      "../../contracts/test/fixtures/core-fixtures.json",
    );
  });
});
