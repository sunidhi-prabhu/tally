// Vendors the parts of @tally/core the indexer uses into src/core/, so the indexer directory is
// self-contained: Envio Cloud uploads only the Indexer Directory and rejects workspace:* deps.
// The copies are byte-identical to packages/core/src apart from a one-line header; `--check`
// fails on any drift. Edit packages/core, then run `pnpm --filter @tally/indexer core:sync`.
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = resolve(ROOT, "../core/src");
const TARGET = join(ROOT, "src/core");
/** Everything ledger.ts needs: the dependency-free accounting modules (no zod schemas). */
export const MODULES = [
  "errors.ts",
  "types.ts",
  "money.ts",
  "members.ts",
  "split.ts",
  "balances.ts",
];

const header = (file) =>
  `// GENERATED from packages/core/src/${file} by scripts/sync-core.mjs. Do not edit here.\n`;
const INDEX =
  "// GENERATED by scripts/sync-core.mjs: the @tally/core subset the indexer uses.\n" +
  MODULES.map((m) => `export * from "./${m.replace(/\.ts$/, "")}";\n`).join("");

const expected = () =>
  new Map([
    ...MODULES.map((m) => [
      m,
      header(m) + readFileSync(join(SOURCE, m), "utf8"),
    ]),
    ["index.ts", INDEX],
  ]);

/** Drift between src/core and packages/core/src; empty when in sync. */
export function checkCore() {
  const want = expected();
  const problems = [];
  for (const [file, content] of want) {
    const path = join(TARGET, file);
    if (!existsSync(path)) problems.push(`missing src/core/${file}`);
    else if (readFileSync(path, "utf8") !== content)
      problems.push(`src/core/${file} differs from packages/core`);
  }
  const present = existsSync(TARGET) ? readdirSync(TARGET) : [];
  for (const file of present)
    if (!want.has(file)) problems.push(`unexpected src/core/${file}`);
  return problems;
}

function main() {
  if (!existsSync(join(SOURCE, "..", "package.json"))) {
    // Isolated checkout (e.g. Envio Cloud uploads only packages/indexer): nothing to compare.
    console.log(
      "packages/core not present (standalone build); using the vendored copy as-is.",
    );
    return;
  }
  if (process.argv.includes("--check")) {
    const problems = checkCore();
    if (problems.length) {
      console.error(
        `${problems.join("\n")}\nRun: pnpm --filter @tally/indexer core:sync`,
      );
      process.exit(1);
    }
    console.log(`Vendored core is in sync (${MODULES.length} modules).`);
  } else {
    mkdirSync(TARGET, { recursive: true });
    for (const [file, content] of expected())
      writeFileSync(join(TARGET, file), content);
    console.log(`Wrote src/core/ (${MODULES.length} modules + index.ts).`);
  }
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  main();
