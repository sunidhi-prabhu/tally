// Generates typed ABIs (`as const` for viem) from the Foundry build into src/lib/contracts/:
// TallyLedger → tallyLedgerAbi.ts, TallyAccount → tallyAccountAbi.ts.
// Run `pnpm --filter @tally/contracts build` first. `--check` fails if either file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CONTRACTS = [
  ["TallyLedger", "tallyLedgerAbi"],
  ["TallyAccount", "tallyAccountAbi"],
];

let stale = false;
for (const [contract, name] of CONTRACTS) {
  const artifact = resolve(
    root,
    `../../packages/contracts/out/${contract}.sol/${contract}.json`,
  );
  const target = resolve(root, `src/lib/contracts/${name}.ts`);
  const abi = JSON.parse(readFileSync(artifact, "utf8")).abi;
  const source =
    "// Generated by scripts/sync-abi.mjs from packages/contracts. Do not edit by hand.\n" +
    `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;

  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {
      // missing counts as stale
    }
    if (current !== source) {
      console.error(
        `${name}.ts is out of date. Run: pnpm --filter @tally/web abi:sync`,
      );
      stale = true;
    }
  } else {
    writeFileSync(target, source);
    console.log(`Wrote ${target}`);
  }
}
if (stale) process.exit(1);
if (process.argv.includes("--check")) console.log("ABI is up to date.");
