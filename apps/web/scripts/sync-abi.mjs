// Generates src/lib/contracts/tallyLedgerAbi.ts (typed `as const` for viem) from the Foundry
// build. Run `pnpm --filter @tally/contracts build` first. `--check` fails if the file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = resolve(
  root,
  "../../packages/contracts/out/TallyLedger.sol/TallyLedger.json",
);
const target = resolve(root, "src/lib/contracts/tallyLedgerAbi.ts");

const abi = JSON.parse(readFileSync(artifact, "utf8")).abi;
const source =
  "// Generated by scripts/sync-abi.mjs from packages/contracts. Do not edit by hand.\n" +
  `export const tallyLedgerAbi = ${JSON.stringify(abi, null, 2)} as const;\n`;

if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== source) {
    console.error(
      "tallyLedgerAbi.ts is out of date. Run: pnpm --filter @tally/web abi:sync",
    );
    process.exit(1);
  }
  console.log("ABI is up to date.");
} else {
  writeFileSync(target, source);
  console.log(`Wrote ${target}`);
}
